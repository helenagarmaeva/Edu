import fs from "node:fs";
const data = JSON.parse(
  fs.readFileSync(
    new URL("../src/design-system/figma.tokens.json", import.meta.url),
  ),
);
const byId = new Map(data.tokens.map((t) => [t.id, t]));
function expression(v, mode = 0, seen = new Set()) {
  if (v.alias) {
    const t = byId.get(`${v.alias.guid.sessionID}:${v.alias.guid.localID}`);
    if (!t) throw Error("Unknown token alias");
    return `var(${t.css})`;
  }
  if (v.colorValue) {
    const c = v.colorValue;
    return `rgb(${["r", "g", "b"].map((k) => Math.round(c[k] * 255)).join(" ")} / ${c.a ?? 1})`;
  }
  if (v.floatValue !== undefined) return `${v.floatValue}px`;
  if (v.textValue !== undefined) return JSON.stringify(v.textValue);
  if (v.expressionValue?.expressionFunction === "COMPOSE_COLOR") {
    const [c, a] = v.expressionValue.expressionArguments;
    return `color-mix(in srgb, ${expression(c.value, mode)} ${a.value.floatValue}%, transparent)`;
  }
  throw Error("Unsupported token value " + JSON.stringify(v));
}
const light = [],
  dark = [];
for (const t of data.tokens) {
  if (!t.modes.length) continue;
  light.push(`  ${t.css}: ${expression(t.modes[0].value)};`);
  if (t.modes[1]) dark.push(`  ${t.css}: ${expression(t.modes[1].value)};`);
}
const css = `/* Generated by npm run tokens. Edit figma.tokens.json, not this file. */\n:root {\n${light.join("\n")}\n}\n[data-theme="dark"] {\n${dark.join("\n")}\n}\n`;
const path = new URL("../src/design-system/figma.tokens.css", import.meta.url);
if (process.argv.includes("--check")) {
  if (fs.readFileSync(path, "utf8") !== css)
    throw Error("Generated tokens are stale");
  console.log(
    `${data.tokens.length} Figma tokens: aliases and generated CSS verified`,
  );
} else fs.writeFileSync(path, css);
const measured = JSON.parse(
  fs.readFileSync(
    new URL("../src/design-system/measured.tokens.json", import.meta.url),
  ),
);
const measuredCSS =
  "/* Residual measured dimensions from component bounds; see source-layout.json. */\n:root {\n" +
  Object.entries(measured)
    .map(([k, v]) => `  ${k}: ${v};\n`)
    .join("") +
  "}\n";
const measuredPath = new URL(
  "../src/design-system/measured.tokens.css",
  import.meta.url,
);
if (process.argv.includes("--check")) {
  if (fs.readFileSync(measuredPath, "utf8") !== measuredCSS)
    throw Error("Measured token CSS is stale");
} else fs.writeFileSync(measuredPath, measuredCSS);
const typeTokens = JSON.parse(
  fs.readFileSync(
    new URL("../src/design-system/typography.tokens.json", import.meta.url),
  ),
);
const typeCSS =
  "/* Resolved Figma text metrics. Generated by npm run tokens. */\n:root {\n" +
  Object.entries(typeTokens)
    .map(
      ([name, t]) =>
        `  --type-${name}-family: "${t.family}";\n  --type-${name}-size: ${t.size}px;\n  --type-${name}-weight: ${t.weight};\n  --type-${name}-line-height: ${t.lineHeight}px;\n  --type-${name}-tracking: ${t.tracking}px;\n`,
    )
    .join("") +
  "}\n";
const typePath = new URL(
  "../src/design-system/typography.tokens.css",
  import.meta.url,
);
if (process.argv.includes("--check")) {
  if (fs.readFileSync(typePath, "utf8") !== typeCSS)
    throw Error("Typography CSS is stale");
} else fs.writeFileSync(typePath, typeCSS);

const cssFiles = [
  "../src/style.css",
  "../src/design-system/figma.tokens.css",
  "../src/design-system/components.css",
  "../src/design-system/measured.tokens.css",
  "../src/design-system/gallery.css",
  "../src/design-system/typography.tokens.css",
]
  .map((p) => fs.readFileSync(new URL(p, import.meta.url), "utf8"))
  .join("\n");
const declared = new Set(
  [...cssFiles.matchAll(/(--[\w-]+)\s*:/g)].map((m) => m[1]),
);
const missing = [...cssFiles.matchAll(/var\((--[\w-]+)/g)]
  .map((m) => m[1])
  .filter((n) => !declared.has(n));
if (missing.length)
  throw Error("Unbound CSS tokens: " + [...new Set(missing)].join(", "));
